fn main() {
    cbindgen::Builder::new()
        .with_crate(env!("CARGO_MANIFEST_DIR"))
        .with_config(cbindgen::Config {
            language: cbindgen::Language::C,
            include_guard: Some("HUAK_PDF_MESH_H".into()),
            autogen_warning: Some("/* Generated by cbindgen. Do not edit. */".into()),
            usize_is_size_t: true,
            ..Default::default()
        })
        .generate()
        .expect("generate mesh encoder header")
        .write_to_file(concat!(env!("CARGO_MANIFEST_DIR"), "/mesh.h"));
}
