fn main() -> Result<(), Box<dyn std::error::Error>> {
    let package = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let output = package.join("include/libtypst.h");
    std::fs::create_dir_all(output.parent().expect("header parent directory"))?;
    let config = cbindgen::Config {
        language: cbindgen::Language::C,
        cpp_compat: true,
        include_guard: Some("LIBTYPST_H".into()),
        autogen_warning: Some("/* Generated by cbindgen. Do not edit by hand. */".into()),
        usize_is_size_t: true,
        ..Default::default()
    };
    cbindgen::Builder::new()
        .with_crate(package)
        .with_config(config)
        .generate()?
        .write_to_file(output);
    Ok(())
}
